// Raw transcription is immutable here. Reviewed amendments are applied only to the public bundle.
import {readFile,writeFile,access} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const sets=[2,3,4,5,7,8,9,10];
const json=async path=>JSON.parse(await readFile(new URL(path,import.meta.url),'utf8'));
const review=await json('./dev/honmen/final-review.json');
const amendments=new Map(review.items.map(r=>[r.id,r]));
assert.equal(amendments.size,review.items.length,'Duplicate amendment');
const terminology=await json('./dev/honmen/moped-terminology.json');
const terms=new Map(terminology.items.map(r=>[r.id,r]));
const categories=['標識・標示','信号・合図','交差点・通行','歩行者保護','速度・車間距離','駐停車','高速道路','二輪車','危険予測','運転・点検','免許・心得'];
const questions=[],audit=[];
for(const set of sets){
  const raw=await json(`./honmen/data/set-${set}.json`);
  assert.equal(raw.length,95,`set ${set}: expected 95`);
  for(const [index,original] of raw.entries()){
    const q=structuredClone(original),r=amendments.get(q.id),term=terms.get(q.id);
    assert.equal(q.id,`h${set}-${String(index+1).padStart(3,'0')}`);
    assert.equal(q.number,index+1);assert.equal(q.set,set);
    assert.equal(q.type,index<90?'boolean':'hazard');
    if(q.status!=='ready')assert.ok(r?.approve&&r.status==='ready',`${q.id}: unresolved review`);
    if(r){
      assert.ok(r.approve&&r.status==='ready',`${q.id}: unapproved amendment`);
      for(const field of ['text','answer','explanation','statements'])if(Object.hasOwn(r,field))q[field]=structuredClone(r[field]);
      q.status='ready';
      if(r.decision==='modify')q.editorial={reason:r.reason,sourceUrls:r.sourceUrls,replacement:!!r.replacement};
    }
    if(term){
      for(const field of term.fields){assert.ok(['text','explanation','statements'].includes(field));assert.ok(Object.hasOwn(term.replacements,field));q[field]=structuredClone(term.replacements[field]);}
      q.editorial={reason:[q.editorial?.reason,term.reason].filter(Boolean).join(' '),sourceUrls:[...new Set([...(q.editorial?.sourceUrls||[]),'https://www.npa.go.jp/bureau/traffic/menkyo/menkyo_nirinsha.html'])],replacement:!!q.editorial?.replacement};
    }
    assert.equal(q.status,'ready');
    for(const field of ['text','explanation'])assert.ok(typeof q[field]==='string'&&q[field].trim(),`${q.id}: ${field}`);
    assert.ok(categories.includes(q.category),`${q.id}: category ${q.category}`);
    assert.ok(Array.isArray(q.sourceImages)&&q.sourceImages.length,`${q.id}: source images`);
    if(q.type==='hazard'){
      assert.equal(q.statements?.length,3);assert.ok(q.statements.every(v=>typeof v==='string'&&v.trim()));
      assert.equal(q.answer?.length,3);assert.ok(q.answer.every(v=>typeof v==='boolean'));
      assert.ok(q.image,`${q.id}: missing hazard image`);
    }else assert.equal(typeof q.answer,'boolean');
    if(q.image){assert.match(q.image,/^honmen\/assets\/h\d+-\d{3}\.jpg$/);await access(new URL('./'+q.image,import.meta.url));assert.ok(q.imageAlt);q.imageHash=createHash('sha256').update(await readFile(new URL('./'+q.image,import.meta.url))).digest('hex');}
    for(const url of q.editorial?.sourceUrls||[])assert.equal(new URL(url).protocol,'https:');
    const fields=['id','set','number','type','text','answer','statements','explanation','category','image','imageAlt','imageHash','status','editorial'];
    const publicQuestion=Object.fromEntries(fields.filter(k=>Object.hasOwn(q,k)).map(k=>[k,q[k]]));
    questions.push(publicQuestion);
    audit.push({id:q.id,sourceText:original.text,sourceAnswer:original.sourceAnswer,sourceStatements:original.statements||null,
      sourceImages:original.sourceImages,transcribedDraft:original.transcribedDraft||null,
      review:r||null,terminology:term||null,publicHash:createHash('sha256').update(JSON.stringify(publicQuestion)).digest('hex')});
  }
}
assert.equal(questions.length,760);assert.equal(new Set(questions.map(q=>q.id)).size,760);
for(const id of amendments.keys())assert.ok(questions.some(q=>q.id===id),`Unknown reviewed id ${id}`);
for(const id of terms.keys())assert.ok(questions.some(q=>q.id===id),`Unknown terminology id ${id}`);
const rules=await json('./honmen/data/rules.json');
const version='honmen-'+createHash('sha256').update(JSON.stringify(questions)).digest('hex').slice(0,12);
const data={version,sets,questions,rules};
const bundle='// Generated by build-honmen.mjs. Do not edit by hand.\nconst HONMEN_DATA = '+JSON.stringify(data)+';\n';
if(process.argv.includes('--check'))assert.equal(await readFile(new URL('./honmen/questions.js',import.meta.url),'utf8'),bundle,'Honmen bundle is stale; run node build-honmen.mjs');
else{
  await writeFile(new URL('./honmen/questions.js',import.meta.url),bundle);
  await writeFile(new URL('./dev/honmen/applied-review.json',import.meta.url),JSON.stringify({version,count:questions.length,audit},null,2)+'\n');
}
console.log(`Honmen: ${questions.length} questions, ${questions.filter(q=>q.type==='hazard').length} hazards, ${version}.`);
